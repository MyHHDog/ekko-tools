// locale 动态解析：测试/嵌入方可通过 window.__ekkoLocale 显式指定（'zh'|'en'），否则跟随 navigator.language。
export type Locale='zh'|'en';
export function currentLocale():Locale{
  if(typeof window!=='undefined'&&(window as any).__ekkoLocale==='en')return 'en';
  if(typeof window!=='undefined'&&(window as any).__ekkoLocale==='zh')return 'zh';
  return (typeof navigator!=='undefined'&&navigator.language?.toLowerCase().startsWith('en'))?'en':'zh';
}
export const locale=currentLocale();
export function t(key:string):string{return currentLocale()==='en'?(en[key]??key):key;}
export function tFormat(key:string,values:Record<string,string|number>):string{
  return t(key).replace(/\{(\w+)\}/g,(_,name)=>String(values[name]??`{${name}}`));
}
